import type { SVGProps } from 'react';

/**
 * 汎用アイコン（ストローク型・currentColor で着色）
 * ページアイコン（leaf / tree / seed）は PageIcon を使う
 */
type IconProps = SVGProps<SVGSVGElement>;

function Icon({ children, strokeWidth = 2, ...props }: IconProps) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      {...props}
    >
      {children}
    </svg>
  );
}

